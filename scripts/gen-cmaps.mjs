// 把 pdfjs-dist/cmaps/*.bcmap 与 standard_fonts/* 以 base64 内联进 src/pdf/cmaps.ts，
// 使中文 CID 字体在离线环境也能正确渲染（不再依赖 CDN）。
// 运行时 pdfjs.ts 会把这些数据注入 worker blob 并拦截 worker 的 fetch 请求。
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { createRequire } from "module";
import { dirname, join } from "path";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("pdfjs-dist/package.json"));

function mapDir(dir) {
  const out = {};
  let total = 0;
  for (const f of readdirSync(dir)) {
    const buf = readFileSync(join(dir, f));
    total += buf.length;
    out[f] = buf.toString("base64");
  }
  return { out, total };
}

const cmaps = mapDir(join(pkgDir, "cmaps"));
const fonts = mapDir(join(pkgDir, "standard_fonts"));

const out = `// AUTO-GENERATED by scripts/gen-cmaps.mjs — 请勿手动编辑
// pdf.js CMap + 标准字体数据（base64），用于离线渲染中文等 CID 字体。
// 解码：atob(b64) -> Uint8Array。
// 共 ${Object.keys(cmaps.out).length} 个 cmaps（${(cmaps.total / 1024).toFixed(1)} KB），${Object.keys(fonts.out).length} 个字体（${(fonts.total / 1024).toFixed(1)} KB）。

export const CMAP_DATA: Record<string, string> = ${JSON.stringify(cmaps.out)};

export const FONT_DATA: Record<string, string> = ${JSON.stringify(fonts.out)};
`;

const outPath = join(process.cwd(), "src", "pdf", "cmaps.ts");
writeFileSync(outPath, out, "utf8");

// 额外生成 cmaps.json，供 esbuild.config.mjs 在物理 worker 文件顶部注入 cMap/字体数据，
// 使离线中文在「物理 worker + file:// 加载」方案下仍生效（不再依赖 blob 注入）。
const jsonPath = join(process.cwd(), "src", "pdf", "cmaps.json");
writeFileSync(jsonPath, JSON.stringify({ cmap: cmaps.out, font: fonts.out }), "utf8");

console.log(
  `Generated ${outPath}: cmaps ${Object.keys(cmaps.out).length} (${(cmaps.total / 1024).toFixed(1)} KB), fonts ${Object.keys(fonts.out).length} (${(fonts.total / 1024).toFixed(1)} KB). Also wrote ${jsonPath}.`
);
