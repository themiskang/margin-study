import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync, writeFileSync, watchFile } from "fs";
import { createRequire } from "module";
import { dirname, join } from "path";
import { execFileSync } from "node:child_process";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("pdfjs-dist/package.json"));
const styleSources = ["styles-base.css", "styles-reader.css", "styles-mindmap.css", "styles-review.css", "styles-import.css", "styles-organize.css", "styles-workspace.css", "styles-ai.css", "styles-research.css"];
function emitStyles() {
  const css = "/* Generated from the named style sources; edit styles-base.css or a feature stylesheet. */\n"
    + styleSources.map(name => "/* Source: " + name + " */\n" + readFileSync(name, "utf8")).join("\n\n") + "\n";
  writeFileSync("styles.css", css, "utf8");
}

// ---- 物理 worker 文件（Obsidian/Electron 不允许 blob: Worker，必须用 file:// 物理文件）----
// cMap/字体数据注入 worker 顶部，离线渲染中文 CID 字体。
const cmapJson = JSON.parse(
  readFileSync(join(process.cwd(), "src", "pdf", "cmaps.json"), "utf8")
);
const CMAP_DATA = cmapJson.cmap;
const FONT_DATA = cmapJson.font;

const WORKER_INJECT = `
const __CMAPS__ = ${JSON.stringify(CMAP_DATA)};
const __FONTS__ = ${JSON.stringify(FONT_DATA)};
(function(){
  function b64ToBytes(b64){ const bin = atob(b64); const len = bin.length; const arr = new Uint8Array(len); for (let i=0;i<len;i++) arr[i]=bin.charCodeAt(i); return arr; }
  const orig = (typeof self !== 'undefined' && self.fetch) ? self.fetch.bind(self) : null;
  const hook = function(input, init){
    const url = (typeof input === 'string') ? input : (input && input.url) || '';
    const lower = String(url).toLowerCase();
    if (lower.indexOf('.bcmap') >= 0) {
      const name = url.substring(url.lastIndexOf('/') + 1);
      const b64 = __CMAPS__[name];
      if (b64) return Promise.resolve(new Response(b64ToBytes(b64)));
    }
    if (lower.endsWith('.pfb') || lower.endsWith('.ttf') || lower.endsWith('.otf') || lower.endsWith('.woff') || lower.endsWith('.woff2')) {
      const name = url.substring(url.lastIndexOf('/') + 1);
      const b64 = __FONTS__[name];
      if (b64) return Promise.resolve(new Response(b64ToBytes(b64)));
    }
    return orig ? orig(input, init) : Promise.reject(new Error('fetch unavailable'));
  };
  if (typeof self !== 'undefined') self.fetch = hook;
  if (typeof globalThis !== 'undefined') globalThis.fetch = hook;
})();
`;

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

function emitWorkerFile() {
  const workerContents = readFileSync(
    join(pkgDir, "build", "pdf.worker.min.js"),
    "utf8"
  );
  const out = WORKER_INJECT + "\n" + workerContents;
  writeFileSync(join(process.cwd(), "pdf.worker.js"), out, "utf8");
  console.log(`Emitted pdf.worker.js (${(out.length / 1024 / 1024).toFixed(2)} MB)`);
}

function copyOcrScript() {
  // ocr.swift 位于工程根目录，构建时不做转换；部署时随插件目录分发即可。
  console.log("ocr.swift ready");
}

const prod = process.argv[2] === "production";
if (process.platform === "darwin") execFileSync(process.execPath, ["scripts/build-native-photos.mjs"], { stdio: "inherit" });
if (process.platform === "darwin") execFileSync(process.execPath, ["scripts/build-native-camera.mjs"], { stdio: "inherit" });
if (process.platform === "darwin") execFileSync(process.execPath, ["scripts/build-native-recall.mjs"], { stdio: "inherit" });

const context = await esbuild.context({
  plugins: [{ name: "package-styles", setup(build) { build.onEnd(result => { if (!result.errors.length) emitStyles(); }); } }],
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: ["obsidian", "electron", ...builtins],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  emitWorkerFile();
  copyOcrScript();
  process.exit(0);
} else {
  emitWorkerFile();
  copyOcrScript();
  emitStyles();
  for (const name of styleSources) watchFile(name, { interval: 500 }, emitStyles);
  await context.watch();
}
