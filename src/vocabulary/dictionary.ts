const index = new Map<string, Omit<VocabularyEntry, "word">>();
for (const row of rows) {
  const [lemma, phonetic, meanings, forms] = row.split("|");
  const entry = { lemma, phonetic, senses: meanings.split(";") };
  for (const word of [lemma, ...(forms ? forms.split(",") : [])]) {
    if (!index.has(word)) index.set(word, entry);
  }
}

export const vocabularySize = rows.length;

export function lookupVocabulary(input: string): VocabularyEntry | undefined {
  const word = input.trim().toLowerCase();
  const entry = index.get(word);
  return entry ? { word, ...entry, senses: [...entry.senses] } : undefined;
}
